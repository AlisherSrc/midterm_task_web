"""Pydantic request and response schemas for Space Bounty Hunters API."""

from datetime import datetime
from pydantic import BaseModel, ConfigDict, Field


# -----------------------------------------------------------------------------
# HuntLog Schemas
# -----------------------------------------------------------------------------
class HuntLogBase(BaseModel):
    criminal_id: int = Field(..., description="Foreign key ID referencing the wanted criminal")
    success: bool = Field(..., description="Whether the criminal was successfully captured")
    notes: str = Field(..., min_length=1, description="Encounter description and mission notes")


class HuntLogCreate(HuntLogBase):
    """Schema for recording a capture attempt.

    NOTE: The creation timestamp MUST be generated by the server,
    not provided by the client.
    """
    pass


class HuntLogUpdate(BaseModel):
    """Schema for partially updating an existing hunt log entry."""
    success: bool | None = Field(default=None, description="Updated capture success status")
    notes: str | None = Field(default=None, min_length=1, description="Updated mission notes")


class HuntLogOut(BaseModel):
    """Schema for returning hunt log details."""
    model_config = ConfigDict(from_attributes=True)

    id: int
    criminal_id: int
    success: bool
    notes: str
    created_at: datetime


# -----------------------------------------------------------------------------
# WantedCriminal Schemas
# -----------------------------------------------------------------------------
class WantedCriminalBase(BaseModel):
    name: str | None = Field(
        default=None,
        description="Real name of the criminal (may be unknown/null)",
    )
    nickname: str = Field(
        ...,
        min_length=1,
        description="Criminal alias or street handle",
        examples=["Vicious", "Red Nova", "Star Phantom"],
    )
    reward: float = Field(
        ...,
        ge=0.0,
        description="Bounty amount in galactic credits",
        examples=[150000.0],
    )
    last_known_coordinates: str | None = Field(
        default=None,
        description="Last known coordinates (latitude, longitude) or location text note",
        examples=["Sector 4, Kepler-22b (-14.234, 120.451) - Abandoned mining outpost"],
    )
    difficulty: int = Field(
        ...,
        ge=1,
        le=10,
        description="Overall difficulty rating (1 to 10)",
        examples=[8],
    )
    armed: bool = Field(
        default=False,
        description="Whether the criminal is heavily armed and dangerous",
    )
    has_crew: bool = Field(
        default=False,
        description="Whether the criminal operates with a crew/syndicate",
    )
    escape_master: bool = Field(
        default=False,
        description="Whether the criminal has a history of high-profile escapes",
    )


class WantedCriminalCreate(WantedCriminalBase):
    """Schema for registering a new bounty."""
    pass


class WantedCriminalOut(WantedCriminalBase):
    """Schema for returning criminal list item."""
    model_config = ConfigDict(from_attributes=True)

    id: int


class WantedCriminalDetailOut(WantedCriminalOut):
    """Schema for returning full criminal details, including capture attempts history."""
    hunt_logs: list[HuntLogOut] = []
